import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const endpoint = "https://steamspy.com/api.php?request=all&page=0";
const response = await fetch(endpoint, { headers: { Accept: "application/json", "User-Agent": "ThirdRailify-Admin catalogue builder" } });
if (!response.ok) throw new Error(`Steam catalogue source returned HTTP ${response.status}.`);
const payload = await response.json();
const games = Object.values(payload || {}).map((item) => ({
  appId: /^\d{1,12}$/.test(String(item?.appid || "")) ? String(item.appid) : "",
  name: clean(item?.name, 160),
  developer: clean(item?.developer, 240),
  publisher: clean(item?.publisher, 240),
  genre: clean(item?.genre, 240),
})).filter((item) => item.appId && item.name);
const unique = [...new Map(games.map((item) => [item.appId, item])).values()].sort((left, right) => Number(left.appId) - Number(right.appId));
if (unique.length < 900) throw new Error(`Steam catalogue source returned only ${unique.length} valid games.`);
const source = `// Generated by scripts/build-steam-fallback-catalogue.mjs from SteamSpy page 0.\n// Contains only bounded public catalogue fields; refresh deliberately, never at request time.\nexport const STEAM_FALLBACK_CATALOGUE = Object.freeze(${JSON.stringify(unique)});\n`;
const output = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../functions/_shared/steam-fallback-catalogue.js");
await writeFile(output, source, "utf8");
console.log(JSON.stringify({ output, games: unique.length, includesWitcher: unique.some((item) => item.appId === "292030"), bytes: Buffer.byteLength(source) }));

function clean(value, max) { return String(value || "").replace(/[\u0000-\u001f\u007f]/g, " ").replace(/\s+/g, " ").trim().slice(0, max); }
